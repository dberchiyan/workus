import { writeFile } from 'node:fs/promises';
import { TOKENS } from '../src/theme/tokens.ts';

/**
 * Generates the Tailwind @theme block from theme/tokens.ts. Colours point at MUI's CSS
 * variables so both systems switch light/dark together; typography utilities are disabled.
 */
const lines: string[] = [];
const push = (name: string, value: string): void => {
  lines.push(`  --${name}: ${value};`);
};

lines.push('/* Generated by scripts/generate-tailwind-theme.ts — do not edit. */');
lines.push('@theme inline {');
for (const reset of [
  'color-*',
  'font-*',
  'text-*',
  'leading-*',
  'tracking-*',
  'font-weight-*',
  'breakpoint-*',
  'radius-*',
]) {
  push(reset, 'initial');
}
for (const [name, px] of Object.entries(TOKENS.breakpoints)) {
  if (px > 0) {
    push(`breakpoint-${name}`, `${px / 16}rem`);
  }
}
for (const [name, px] of Object.entries(TOKENS.radius)) {
  push(`radius-${name}`, `${px / 16}rem`);
}
for (const [name, px] of Object.entries(TOKENS.layout)) {
  push(`spacing-${name.replace(/[A-Z]/g, (c) => `-${c.toLowerCase()}`)}`, `${px / 16}rem`);
}
for (const [name, px] of Object.entries(TOKENS.containers)) {
  push(`container-${name}`, `${px / 16}rem`);
}
for (const [group, value] of Object.entries(TOKENS.colors.light)) {
  if (typeof value === 'string') {
    push(`color-${group}`, `var(--mui-palette-${group})`);
  } else {
    for (const shade of Object.keys(value)) {
      const suffix =
        shade === 'main' || shade === 'default'
          ? ''
          : `-${shade.replace(/[A-Z]/g, (c) => `-${c.toLowerCase()}`)}`;
      push(`color-${group}${suffix}`, `var(--mui-palette-${group}-${shade})`);
    }
  }
}
lines.push('}');

await writeFile(
  new URL('../src/theme/tailwind.theme.css', import.meta.url),
  `${lines.join('\n')}\n`,
);
